// The text `key` of an experience (`_` for the shared ones) in the language in use.
export function et(id, key, vars = {}) {
  const table = TEXT[id] ?? {};
  const lang = getLanguage();
  let value = table[lang]?.[key] ?? table["pt-BR"]?.[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

// `eic.<id>.<key>` strings (also `eic._.<key>`), for the views that translate by key.
registerResolver((key, lang) => {
  const m = /^eic\.([^.]+)\.(.+)$/.exec(key);
  if (!m || !TEXT[m[1]]) return undefined;
  return TEXT[m[1]][lang]?.[m[2]] ?? TEXT[m[1]]["pt-BR"]?.[m[2]];
});
